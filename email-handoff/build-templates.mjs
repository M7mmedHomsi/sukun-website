/* Turns templates/*.html and templates/*.txt into waitlist/templates.ts.
   Supabase bundles a function's directory, but reading files at runtime
   differs between local serve and deployed, so the safest thing is to have
   the HTML already be TypeScript. Run: node build-templates.mjs */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const read = (f) => readFileSync(join(here, 'templates', f), 'utf8').trim();

// A template literal ends at an unescaped backtick and interpolates at ${.
const lit = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';

const langs = ['ar', 'en'];
const subjects = {
  ar: 'أنت على قائمة الانتظار، وهدية ترحيبية بانتظارك في الداخل',
  en: 'Welcome to Sukun | Enjoy your gift'
};

const body = langs.map((l) => `  ${l}: {
    subject: ${lit(subjects[l])},
    html: ${lit(read(`welcome-${l}.html`))},
    text: ${lit(read(`welcome-${l}.txt`))}
  }`).join(',\n');

const ts = `// GENERATED by email-handoff/build-templates.mjs — do not edit by hand.
// Edit email-handoff/templates/*.html and *.txt, then re-run the script.

export type Lang = "ar" | "en";

export interface Template {
  subject: string;
  html: string;
  text: string;
}

const TEMPLATES: Record<Lang, Template> = {
${body}
};

/** Fills the two placeholders the templates ship with. */
export function render(lang: Lang, vars: { unsubscribeUrl: string; postalAddress: string }): Template {
  const t = TEMPLATES[lang] ?? TEMPLATES.ar;
  const fill = (s: string) =>
    s.replaceAll("__UNSUBSCRIBE_URL__", vars.unsubscribeUrl)
     .replaceAll("__POSTAL_ADDRESS__", vars.postalAddress);
  return { subject: t.subject, html: fill(t.html), text: fill(t.text) };
}
`;

mkdirSync(join(here, 'waitlist'), { recursive: true });
writeFileSync(join(here, 'waitlist', 'templates.ts'), ts, 'utf8');
console.log('wrote waitlist/templates.ts  (' + Math.round(ts.length / 1024) + ' KB)');
